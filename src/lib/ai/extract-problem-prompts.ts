export function buildExtractPrompt(source: ExtractSource, extractType: string | null): string {
  if (extractType === 'eng_eng_def') {
    return `${HEADER_ENG_ENG_DEF[source]}\n${RULES_ENG_ENG_DEF}`;
  }
  return `${HEADER[source]}\n\n${RULES_DEFAULT}`;
}

